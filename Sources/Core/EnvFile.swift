import Foundation

// MARK: - env.txt (per-game nxnative configuration)
//
// Format: `KEY=value`, comments start with `#`.
// Keys the app does not manage (e.g. debug variables) are preserved on save.

struct EnvFile {
    private(set) var lines: [String]

    init(contents: String = "") {
        var all = contents.components(separatedBy: "\n")
        while let last = all.last, last.trimmingCharacters(in: .whitespaces).isEmpty {
            all.removeLast()
        }
        lines = all
    }

    static func load(path: String) -> EnvFile? {
        guard let content = try? String(contentsOfFile: path, encoding: .utf8) else { return nil }
        return EnvFile(contents: content)
    }

    /// Splits an active line into key and value (comments/empty lines → nil).
    static func parse(_ line: String) -> (key: String, value: String)? {
        let trimmed = line.trimmingCharacters(in: .whitespaces)
        guard !trimmed.isEmpty, !trimmed.hasPrefix("#") else { return nil }
        let parts = trimmed.split(separator: "=", maxSplits: 1).map(String.init)
        guard parts.count == 2 else { return nil }
        return (parts[0].trimmingCharacters(in: .whitespaces), parts[1].trimmingCharacters(in: .whitespaces))
    }

    /// All active values (for duplicate keys the last one wins, like in a shell).
    var values: [String: String] {
        var result: [String: String] = [:]
        for line in lines {
            if let entry = Self.parse(line) { result[entry.key] = entry.value }
        }
        return result
    }

    /// Lines that don't belong to the managed keys (including user comments).
    /// Comment lines generated by the app itself are filtered out.
    func unmanagedLines(managedKeys: Set<String>) -> [String] {
        lines.filter { line in
            let trimmed = line.trimmingCharacters(in: .whitespaces)
            if trimmed.isEmpty { return false }
            if let entry = Self.parse(line) { return !managedKeys.contains(entry.key) }
            // Comment lines generated by the app (current and older versions)
            if trimmed.hasPrefix("# nxnative") { return false }
            if managedKeys.contains(where: { trimmed.hasPrefix("# \($0)") }) { return false }
            if Self.generatedCommentLines.contains(trimmed) { return false }
            return true
        }
    }

    /// Section header written above preserved (unmanaged) entries.
    static let preservedHeader = "# --- Additional entries ---"

    /// Comment lines the app writes itself. The header line is localized at write time
    /// (German/English UI), and 1.1.0 used a bilingual section header – all variants are
    /// recognized so they are not duplicated on the next save.
    private static let generatedCommentLines: Set<String> = [
        preservedHeader,
        "# --- Weitere Einträge / Additional entries ---",
        "# Wird automatisch beim Start des Spiels ausgelesen",
        "# Automatically detected when the game starts"
    ]
}
